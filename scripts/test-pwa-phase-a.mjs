import assert from "node:assert/strict";
import {readFileSync,existsSync} from "node:fs";
const read=(p)=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const manifest=JSON.parse(read("manifest.webmanifest"));
assert.equal(manifest.scope,"/");
assert.equal(manifest.display,"standalone");
assert(manifest.start_url.startsWith("/"));
assert(manifest.icons.some(i=>i.purpose==="maskable"));
for(const icon of manifest.icons)assert(existsSync(new URL(".."+icon.src,import.meta.url)),"Missing "+icon.src);
const home=read("index.html");
assert(home.includes("/assets/site.js"));
const site=read("assets/site.js");
assert(site.includes("/assets/pwa-mobile.js"));
assert(site.includes("/assets/pwa-mobile.css"));
const bootstrap=read("assets/pwa-mobile.js");
assert(bootstrap.includes('link.rel="manifest"'));
assert(bootstrap.includes('serviceWorker.register("/sw.js"'));
assert(bootstrap.includes('display-mode: standalone'));
assert(bootstrap.includes('blocked.test(location.pathname)'));
const sw=read("sw.js");
assert(sw.includes('request.mode !== "navigate"'));
assert(sw.includes('request.method !== "GET"'));
assert(sw.includes('url.origin !== self.location.origin'));
assert(sw.includes('PRIVATE.test(url.pathname)'));
assert(!/cache\.put\s*\(/.test(sw),"No response bodies may be cached");
assert(!/caches\.match\(request/.test(sw),"Do not cache URL responses");
assert(read("offline.html").includes('name="robots" content="noindex,nofollow"'));
console.log("PASS: PWA manifest, icon paths, app-only navigation, privacy-safe offline fallback, and bootstrap.");

import {readFileSync,writeFileSync} from 'node:fs';
const root=new URL('../slashview-backend/',import.meta.url);
let source=readFileSync(new URL('worker.js',root),'utf8');
for(const [name,file] of [['accessOwner','access-owner.js'],['verifyGoogle','google-identity.js']]){
 const module=readFileSync(new URL(file,root),'utf8').replace('export async function','async function');
 source=source.replace(`import {${name}} from "./${file}";`,`const ${name} = (() => {\n${module}\nreturn ${name};\n})();`);
}
source='// Generated by scripts/build-slashview-backend.mjs; edit worker.js and its modules.\n'+source;
const dest=new URL('dashboard-worker.js',root);
if(process.argv.includes('--check')){if(readFileSync(dest,'utf8')!==source)throw Error('Deployment bundle is stale');}
else writeFileSync(dest,source);
